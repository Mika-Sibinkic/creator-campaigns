/**
 * Creator Campaigns Outreach Message Generation
 *
 * ONE hardened path to a creator-facing draft.
 *
 * History: this module used to be a
 * SECOND, unguarded generator sitting behind the /outreach page's "Generate"
 * buttons. It had no banned-tell list, no "recent" ban, no authorship verdict,
 * and it never called checkDraftCopy — so while the campaign page's
 * "Generate drafts" ran the hardened src/lib/openai.ts path, every draft made
 * from /outreach bypassed the validator entirely. Nothing on that path
 * stopped a songwriter's own single being attributed to the promoted artist,
 * her original being called a "take", old posts pitched as "recent", "~$0"
 * offers out of a `price_estimate_mid || 0` default, or the per-creator
 * budget cap printed into creator-facing copy.
 *
 * The rules now, structurally:
 *   1. `initial` drafts are generated by the hardened generateOutreachDraft()
 *      in src/lib/openai.ts. There is no second prompt.
 *   2. `follow_up` / `negotiation` copy carries the same anti-tell rules and
 *      every draft — including the initial one — is re-checked by
 *      checkOutreachCopy() before it is returned. Failing copy gets one
 *      constrained retry, then a deterministic safe fallback.
 *   3. No price appears in copy unless a real price exists. There is no
 *      numeric default; `price_estimate_mid` is `number | null`, and the
 *      validator rejects any money at all when it is null.
 *   4. A creator the qualification pass excluded can never be drafted to, and
 *      an unreviewed creator is qualified on demand rather than silently
 *      pitched. See resolveEligibility().
 *
 * SEC-1: this lib no longer imports the eager `supabase` (anon, no-JWT) client.
 * User-path callers MUST pass a SupabaseClient that already carries the
 * session JWT — RLS then enforces firm scope automatically. The pipeline
 * path (which acts as the system) passes the service-role admin client.
 */
