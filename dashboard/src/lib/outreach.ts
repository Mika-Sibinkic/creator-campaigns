/** Coerce a Postgres numeric (number | string | null) to a usable price, or null. */
function toPrice(v: unknown): number | null {
  const n = typeof v === "string" ? Number(v) : typeof v === "number" ? v : NaN;
  return Number.isFinite(n) && n > 0 ? n : null;
}

function toQualification(v: unknown): QualificationStatus {
  return v === "qualified" || v === "excluded" ? v : "unreviewed";
}

async function loadInfluencerContext(
  sb: SupabaseClient,
  campaignInfluencerId: string
): Promise<InfluencerContext | null> {
  // Load campaign_influencer with influencer join
  const { data: ci } = await sb
    .from("campaign_influencers")
    .select("*, influencer:influencers(*)")
    .eq("id", campaignInfluencerId)
    .single();

  if (!ci || !ci.influencer) return null;

  // Load campaign
  const { data: campaign } = await sb
    .from("campaigns")
    .select("*")
    .eq("id", ci.campaign_id)
    .single();

  if (!campaign) return null;

  // Load firm context
  const { data: firmCtx } = await sb
    .from("firm_contexts")
    .select("*")
    .eq("firm_id", campaign.firm_id)
    .single();

  // Per-firm pool gates: the follower cap and audience-fit
  // minimum apply at DRAFT time too — the shared influencers table can hold
  // rows outside this firm's caps. Missing/malformed prefs resolve to the
  // documented defaults.
  //
  // Also the identity + voice the first touch needs. `name` and `sender_name`
  // are here because the body has to say who is writing: without them the copy
  // said "we're promoting" and named nobody, which is the shape of a scam.
  // `outreach_prefs` is here because the label filled that form in and, until
  // now, only one field of it (in the wrong slot) ever reached a prompt.
  // Same row, same round trip.
  const { data: firmRow } = await sb
    .from("firms")
    .select("scraping_prefs, name, sender_name, outreach_prefs, voice_profile")
    .eq("id", campaign.firm_id)
    .single();
  const firm = firmRow as {
    scraping_prefs?: unknown;
    name?: string | null;
    sender_name?: string | null;
    outreach_prefs?: unknown;
    voice_profile?: unknown;
  } | null;
  const gatePrefs = resolvePoolGatePrefs(firm?.scraping_prefs);

  // Per-label do-not-contact (migration 056). Unreadable → gate on the global
  // flag alone: this path PERSISTS an exclusion, so failing closed here would
  // exclude creators on a blip. The send boundary and dispatch re-check and
  // fail closed, so nothing is sent on a guess.
  const firmBlocks = await readFirmBlocks(sb, campaign.firm_id, [ci.influencer.id]);
  if (firmBlocks.state === "unreadable") {
    console.error("[outreach] firm block list unreadable, drafting on the global flag only", firmBlocks.message);
  }

  // Load previous messages for this influencer in this campaign
  const { data: prevMessages } = await sb
    .from("outreach_messages")
    .select("direction, body, classification")
    .eq("campaign_influencer_id", campaignInfluencerId)
    .order("created_at", { ascending: true });

  const inf = ci.influencer;
  const rawData = (inf.raw_data ?? null) as { posts?: QualifyRawPost[] } | null;
  // influencers has no `following` column; the scrape carries it on the first
  // post's authorMeta (same read the pipeline's qualification step does).
  const authorMeta = (rawData?.posts?.[0] as { authorMeta?: { following?: number } } | undefined)
    ?.authorMeta;

  return {
    campaign_influencer_id: campaignInfluencerId,
    campaign_id: ci.campaign_id,
    influencer_id: inf.id,
    username: inf.username,
    display_name: inf.display_name || inf.username,
    platform: inf.platform,
    primary_channel: ci.primary_channel ?? null,
    follower_count: inf.follower_count || 0,
    following_count: typeof authorMeta?.following === "number" ? authorMeta.following : null,
    engagement_rate: inf.engagement_rate || 0,
    verified: inf.verified === true,
    bio: inf.bio || "",
    contact_email: inf.contact_email,
    composite_score: ci.composite_score || 0,
    tier: ci.tier || "C",
    outreach_angle: ci.outreach_angle || "",
    bot_flagged: ci.bot_flagged === true || inf.bot_flagged === true,
    blocklisted: inf.blocklisted === true || firmBlocks.ids.has(inf.id),
    qualification_status: toQualification(ci.qualification_status),
    qualification_reason: ci.qualification_reason ?? null,
    audience_fit: audienceFitOf(ci.score_breakdown),
    gate_prefs: gatePrefs,
    raw_data: rawData,
    price_estimate_mid: toPrice(ci.price_estimate_mid),
    artist_name: campaign.artist_name,
    track_name: campaign.track_name ?? null,
    release_date: campaign.release_date ?? null,
    // No genre data → say nothing. A defaulted genre would pitch an EDM label
    // as "aligning perfectly" with some other genre's music.
    genre: (campaign.artist_data as Record<string, string>)?.genre || "",
    voice_profile: firmCtx?.voice_profile || "professional",
    budget: toPrice(campaign.budget),
    per_influencer_cap: toPrice(campaign.per_influencer_cap),
    special_instructions: campaign.special_instructions,
    previous_messages: prevMessages || [],
    firm_name: firm?.name ?? null,
    sender_name: firm?.sender_name ?? null,
    voice_prefs: resolveOutreachVoicePrefs(
      firm?.outreach_prefs,
      firm?.voice_profile,
      firm?.name ?? null
    ),
  };
}

// ── Standing package ────────────────────────────────────────────────────────

/**
 * THE package a draft is allowed to name, resolved through the same
 * resolveStandingDeliverables() the negotiator prices against, the counter and
 * acceptance copy restate, and the agreement freezes onto the offer row
 * (src/lib/deliverables-store.ts).
 *
 * This path must not name a package of its own. If the pitch and the store
 * disagree, the creator is pitched one package and contracted another, and a
 * creator's yes is to the email they read.
 *
 * Precedence is the store's, not ours: a package frozen on the offer by a term
 * trade wins, then offer-level line items, then the campaign template, then the
 * default bundle. Never throws — a read hiccup degrades to the campaign/default
 * package rather than blocking a draft.
 */
async function standingDeliverables(
  sb: SupabaseClient,
  ctx: InfluencerContext
): Promise<Deliverable[]> {
  let offer: { id: string | null; campaign_id: string; agreed_deliverables?: unknown } = {
    id: null,
    campaign_id: ctx.campaign_id,
  };
  try {
    const { data } = await sb
      .from("creator_offers")
      .select("id, agreed_deliverables")
      .eq("campaign_influencer_id", ctx.campaign_influencer_id)
      .maybeSingle();
    const row = data as { id?: string | null; agreed_deliverables?: unknown } | null;
    if (row) {
      offer = {
        id: row.id ?? null,
        campaign_id: ctx.campaign_id,
        agreed_deliverables: row.agreed_deliverables,
      };
    }
  } catch {
    // No offer row yet (the usual case before a deal), or a read hiccup. The
    // campaign template / default bundle still answers the question correctly.
  }
  return resolveStandingDeliverables(sb, offer);
}

// ── Eligibility gate ────────────────────────────────────────────────────────

/**
 * Decide whether this creator may receive a message, and refuse loudly if not.
 *
 * Why qualify on demand rather than refuse every 'unreviewed' row:
 * the pipeline's qualification step only covers the TOP 25 ranked creators
 * (QUALIFY_MAX_CREATORS in api/campaigns/[id]/run), so most rows stay
 * 'unreviewed'. Refusing on 'unreviewed' would refuse nearly every
 * draft in the system — a copy-quality fix turned into an outage. Instead the
 * gap closes at the only moment that matters, the moment a message would be
 * written to a human: one qualifyCreator() call, verdict persisted so each
 * creator is decided once, and the deterministic pre-checks (no posts /
 * long-dead account) decide many rows with no model call at all.
 *
 * qualifyCreator() never throws and is fail-open by construction — when the
 * model is unavailable it returns confidence 0, which maps to 'unreviewed'.
 * We keep that posture (blocking on a model outage would be worse), but the
 * draft is then explicitly labelled `qualification: 'unreviewed'` in the
 * response and the audit record instead of pretending the creator was vetted.
 */
async function resolveEligibility(
  sb: SupabaseClient,
  ctx: InfluencerContext
): Promise<QualificationStatus> {
  if (ctx.bot_flagged) {
    throw new DraftRefusedError({
      reason_code: "bot_flagged",
      message: `@${ctx.username} is flagged as a bot account and will not be drafted to.`,
      qualification_status: ctx.qualification_status,
    });
  }

  if (ctx.qualification_status === "excluded") {
    throw new DraftRefusedError({
      reason_code: "excluded",
      message:
        ctx.qualification_reason ||
        `@${ctx.username} was excluded by the qualification pass and will not be drafted to.`,
      qualification_status: "excluded",
    });
  }

  // Per-firm pool gates, checked BEFORE the stored
  // 'qualified' shortcut on purpose: rows qualified before the gates existed
  // (or under different firm prefs) can sit over the current follower cap or
  // under the audience-fit minimum, and a message must never be written to
  // them. Deterministic, zero model calls; the exclusion persists so the row
  // leaves every pool and keeps an inspectable reason.
  const gate = poolGateExclusion(
    {
      followers: ctx.follower_count,
      audience_fit: ctx.audience_fit,
      blocklisted: ctx.blocklisted,
    },
    ctx.gate_prefs
  );
  if (gate) {
    try {
      await sb
        .from("campaign_influencers")
        .update(gateExclusionPatch(gate) as never)
        .eq("id", ctx.campaign_influencer_id);
    } catch {
      /* ignore — the gate below still applies */
    }
    throw new DraftRefusedError({
      reason_code: "excluded",
      message: gate.reason,
      qualification_status: "excluded",
    });
  }

  if (ctx.qualification_status === "qualified") return "qualified";

  // 'unreviewed' → decide it now.
  const verdict = await qualifyCreator(
    {
      username: ctx.username,
      display_name: ctx.display_name,
      bio: ctx.bio,
      followers: ctx.follower_count,
      following: ctx.following_count,
      engagement_rate: ctx.engagement_rate,
      verified: ctx.verified,
      raw_data: ctx.raw_data,
      campaign: {
        id: ctx.campaign_id,
        artist_name: ctx.artist_name,
        track_name: ctx.track_name,
        genre: ctx.genre || null,
      },
    },
    { excludeMusicArtists: ctx.gate_prefs.exclude_music_artists }
  );
  const status = statusForVerdict(verdict);

  if (status !== "unreviewed") {
    // Best-effort persistence: the verdict is worth keeping, but a write
    // failure must not change the decision we already made.
    try {
      await sb
        .from("campaign_influencers")
        .update({
          qualification_status: status,
          qualification_reason: verdict.reason,
          qualification_confidence: verdict.confidence,
        } as never)
        .eq("id", ctx.campaign_influencer_id);
    } catch {
      /* ignore — the gate below still applies */
    }
  }

  if (status === "excluded") {
    throw new DraftRefusedError({
      reason_code: "excluded",
      message: verdict.reason,
      qualification_status: "excluded",
    });
  }
  return status;
}

// ── Copy validator ──────────────────────────────────────────────────────────

/** `$1,200`, `$0`, `$450.50`, `1200 USD`, `0 dollars`. */
const MONEY_RE =
  /\$\s*([0-9][0-9,]*(?:\.[0-9]{1,2})?)|\b([0-9][0-9,]*(?:\.[0-9]{1,2})?)\s*(?:usd|dollars?)\b/gi;

/** Internal-economics vocabulary that must never be visible to a creator. */
const CONFIDENTIAL_TELLS: RegExp[] = [
  /\bbudgets?\b/i,
  /\b(?:price|spend|per[- ]?(?:creator|influencer))\s+caps?\b/i,
  /\bcaps?\b/i,
  /\bceilings?\b/i,
  /\bmax(?:imum)?\s+(?:we|i)\s+can\b/i,
  /\bup to \$\s*[0-9]/i,
];

function moneyAmounts(text: string): number[] {
  const out: number[] = [];
  MONEY_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = MONEY_RE.exec(text)) !== null) {
    const raw = (m[1] ?? m[2] ?? "").replace(/,/g, "");
    const n = Number(raw);
    if (Number.isFinite(n)) out.push(n);
  }
  return out;
}

function fmtUsd(n: number): string {
  return Number.isInteger(n) ? `$${n}` : `$${n.toFixed(2)}`;
}

export interface OutreachCopyCheckInput {
  subject: string | null;
  body: string;
  artistName: string;
  trackName?: string | null;
  creatorBio?: string | null;
  creatorIsAuthor: boolean;
  releasePast: boolean;
  /**
   * The ONE price the creator may see, or null when no real price exists.
   * null means the copy must name no money at all — that is what makes a
   * "~$0" pitch structurally impossible rather than merely discouraged.
   */
  priceUsd: number | null;
  /** Internal ceilings (campaign budget, per-creator cap) that must not leak. */
  confidentialAmounts?: (number | null | undefined)[];
}

/**
 * The deterministic gate EVERY creator-facing draft clears, whichever message
 * type produced it. Layer 1 is the shared checkDraftCopy() from
 * src/lib/openai.ts — the same validator the campaign draft path uses, so
 * there is one banned-tell list, not two. Layer 2 is the money rules, which
 * live here because they need the campaign's economics.
 *
 * Returns human-readable violations; empty array = clean.
 */
export function checkOutreachCopy(input: OutreachCopyCheckInput): string[] {
  const subject = input.subject ?? "";
  const violations = checkDraftCopy({
    body: input.body,
    subject,
    artistName: input.artistName,
    trackName: input.trackName ?? null,
    creatorBio: input.creatorBio ?? null,
    creatorIsAuthor: input.creatorIsAuthor,
    releasePast: input.releasePast,
  });

  const text = `${subject}\n${input.body}`;
  const amounts = moneyAmounts(text);
  const price = input.priceUsd;

  for (const a of amounts) {
    if (a <= 0) {
      violations.push(
        `proposes ${fmtUsd(a)} to a creator. A draft must never name a zero or negative amount`
      );
    }
  }

  if (price === null) {
    for (const a of amounts) {
      if (a > 0) {
        violations.push(
          `names ${fmtUsd(a)} when this campaign has no verified price for the creator. No price may appear`
        );
      }
    }
  } else {
    for (const a of amounts) {
      if (a > 0 && Math.abs(a - price) >= 1) {
        violations.push(
          `names ${fmtUsd(a)}, which is not the proposed price (${fmtUsd(price)}). The proposed price is the only number a creator sees`
        );
      }
    }
    for (const c of input.confidentialAmounts ?? []) {
      if (typeof c !== "number" || !Number.isFinite(c)) continue;
      if (Math.abs(c - price) < 1) continue; // the price legitimately equals it
      if (amounts.some((a) => Math.abs(a - c) < 1)) {
        violations.push(`leaks an internal ceiling (${fmtUsd(c)}) into creator-facing copy`);
      }
    }
  }

  for (const re of CONFIDENTIAL_TELLS) {
    const m = text.match(re);
    if (m) violations.push(`names internal economics ("${m[0]}") to a creator`);
  }

  return violations;
}

