/**
 * The anti-tell rules, kept verbatim-equivalent to the hardened generator's so
 * the prompt and the validator agree. These are a best-effort steer; the
 * enforcement is checkOutreachCopy(), because prompt-only bans measurably leak.
 */
const COPY_RULES = [
  "- No em dashes anywhere. Use periods or commas.",
  "- No hype or flattery words (thrilled, excited, amazing, incredible, obsessed, huge fan, vibrant).",
  '- No "I hope this finds you well", no "hope you\'re doing well", no "I wanted to reach out".',
  '- Never use the word "recent" or claim recency about their posts.',
  "- Never claim to have watched a specific video. You have not.",
  "- Never call the creator's own work a take, cover, version, rendition, or spin on anything.",
  "- Do not stack three compliments or three-part lists.",
  "- Contractions are good. Slightly imperfect and human beats polished and robotic.",
  "- Never mention a budget, a cap, a ceiling, or the most you can pay.",
].join("\n");

const COPY_SYSTEM =
  "You write short, human outreach and negotiation messages from a music label to a creator. " +
  "Follow the user's instructions exactly. Sound like a real person, not a marketing bot.";

function priceRules(price: number | null): string {
  return price === null
    ? "- Do NOT name a price, a number, or any dollar amount. There is no agreed figure yet, so ask what their usual rate is for this kind of post."
    : `- The ONLY money figure you may write is ${fmtUsd(price)}. No other number, no range, no ceiling.`;
}

/**
 * The package rule, phrased the way the counter-copy generator phrases it
 * (negotiation-tick's "The deal is for: ..."), so a creator reads the same
 * sentence shape from the first pitch to the acceptance email.
 *
 * Safe to interpolate: describeDeliverables() emits enum labels and integers
 * only. It deliberately ignores `schedule_note`, the one creator-controlled
 * string a Deliverable can carry, so nothing from a creator's reply crosses the
 * data fence into a prompt here (src/lib/injection-guard.ts).
 */
function packageRules(ask: string): string {
  return ask
    ? `- The deal is for: ${ask}. State that deliverable ask plainly, exactly as written. Do not invent a different format, quantity, length, or timeline.`
    : "- Do NOT name deliverables or a timeline. Ask what they would be up for instead.";
}

function threadSummary(ctx: InfluencerContext, chars: number): string {
  return (
    ctx.previous_messages
      .map(
        (m) =>
          `[${m.direction.toUpperCase()}]: ${m.body.slice(0, chars)}${
            m.body.length > chars ? "..." : ""
          }`
      )
      .join("\n\n") || "No previous messages."
  );
}

/**
 * campaigns.special_instructions, made real.
 *
 * The field has been written by the new-campaign form, validated, persisted,
 * cloned and read into InfluencerContext since the beginning, and interpolated
 * into exactly zero prompts — while the form told the label it feeds "the AI
 * discovery engine". That is worse than
 * having no field: the label wrote an instruction, watched it save, and it did
 * nothing.
 *
 * It belongs HERE, in copy generation, and deliberately nowhere else. It is
 * free text, so it can shape voice, framing and what to mention — it cannot
 * express a bound, and the thing it kept getting confused with (what the
 * negotiator is allowed to agree to) is now structured data on
 * promo_deliverables, which is enforceable. Feeding free text to the
 * negotiator would only bias a classifier that has a fixed output schema,
 * while widening what reaches a model on the most sensitive path in the app.
 *
 * Trust level: first-party (the label's own staff typed it), the same seam
 * custom_instructions already rides. No injection fence — that is for creator
 * text. Whitespace-collapsed and capped so one pasted essay cannot crowd out
 * the rules below it, and the copy validator still runs on the output either
 * way.
 */
const LABEL_NOTES_MAX_CHARS = 1000;

export function labelNotes(
  specialInstructions: string | null | undefined,
  customInstructions?: string,
): string | undefined {
  const parts = [specialInstructions, customInstructions]
    .map((p) => (typeof p === "string" ? p.replace(/\s+/g, " ").trim() : ""))
    .filter((p) => p.length > 0);
  if (parts.length === 0) return undefined;
  return parts.join(" ").slice(0, LABEL_NOTES_MAX_CHARS);
}

function buildFollowUpPrompt(
  ctx: InfluencerContext,
  channel: string,
  packageAsk: string,
  customInstructions?: string
): string {
  const lastResponse = ctx.previous_messages.filter((m) => m.direction === "inbound").pop();
  const responseContext = lastResponse
    ? `Their last response was classified as: ${lastResponse.classification || "unknown"}`
    : "They haven't responded yet.";

  return `Write a ${channel === "email" ? "brief follow-up email" : "short follow-up DM"} to a creator about a music promotion collaboration.

## Previous Conversation
${threadSummary(ctx, 200)}

## Context
${responseContext}
- Artist: ${ctx.artist_name}${ctx.genre ? ` (${ctx.genre})` : ""}
- Creator: @${ctx.username} on ${ctx.platform}

## Rules
${COPY_RULES}
${priceRules(null)}
- Never invent specifics about their content.
- ${
    lastResponse?.classification === "interested"
      ? `Move toward specifics. ${packageRules(packageAsk).replace(/^- /, "")}`
      : lastResponse?.classification === "question"
      ? "Answer their question naturally and keep the conversation going."
      : "Gently re-engage without being pushy."
  }
- ${channel === "email" ? "Keep under 100 words." : "Keep under 60 words."}
${customInstructions ? `\n## Additional Instructions\n${customInstructions}` : ""}

Output JSON only: {"subject": "...", "body": "..."}${
    channel === "email" ? "" : ' (subject is ignored for a DM; send "").'
  }`;
}

function buildNegotiationPrompt(
  ctx: InfluencerContext,
  channel: string,
  price: number | null,
  packageAsk: string,
  customInstructions?: string
): string {
  return `Write a ${channel === "email" ? "negotiation email" : "negotiation DM"} for a micro-influencer deal on a music promotion campaign.

## Conversation So Far
${threadSummary(ctx, 200)}

## Deal Parameters
- Artist: ${ctx.artist_name}${ctx.genre ? ` (${ctx.genre})` : ""}
- Creator: @${ctx.username} (${ctx.follower_count.toLocaleString()} followers)

## Rules
${COPY_RULES}
${priceRules(price)}
${packageRules(packageAsk)}
- Be flexible on how they make it, never on what the deal covers.
- ${channel === "email" ? "Keep under 120 words." : "Keep under 80 words."}
${customInstructions ? `\n## Additional Instructions\n${customInstructions}` : ""}

Output JSON only: {"subject": "...", "body": "..."}${
    channel === "email" ? "" : ' (subject is ignored for a DM; send "").'
  }`;
}

// ── Deterministic safe fallbacks ────────────────────────────────────────────
// Used when two generations both fail the validator. Plain, true, priceless
// (literally, unless a real price exists) — and themselves validator-clean.

function fallbackFollowUp(ctx: InfluencerContext): { subject: string; body: string } {
  return {
    subject: `Following up on ${ctx.artist_name}`,
    body: [
      `Hi @${ctx.username},`,
      "",
      `Circling back on the ${ctx.artist_name} collab. Still happy to make it work if you're open to it.`,
      "",
      "Reply here and we'll sort the details.",
    ].join("\n"),
  };
}

function fallbackNegotiation(
  ctx: InfluencerContext,
  price: number | null,
  packageAsk: string
): { subject: string; body: string } {
  // Same resolved package as the prompt above, so degrading to safe copy can
  // never quietly change what the creator is being asked to make.
  const scope = packageAsk || "a paid promo";
  const offer =
    price === null
      ? `What's your usual rate to feature the song in ${scope}?`
      : `We can pay ${fmtUsd(price)} to feature the song in ${scope}.`;
  return {
    subject: `Terms for the ${ctx.artist_name} collab`,
    body: [`Hi @${ctx.username},`, "", offer, "", "If that works, reply and we'll send the details."].join(
      "\n"
    ),
  };
}

// ── Generation ──────────────────────────────────────────────────────────────

async function generateJson(
  system: string,
  user: string,
  purpose: string,
  campaignId: string | null
): Promise<{ subject: string; body: string }> {
  const parsed = (await complete({
    system,
    user,
    schema: { subject: "string", body: "string" },
    temperature: 0.6,
    purpose,
    campaign_id: campaignId,
  })) as { subject?: string; body?: string };
  // Em dashes rewritten before validation and storage (no-em-dash.ts).
  return {
    subject: stripEmDashes((parsed.subject ?? "").trim()),
    body: stripEmDashes((parsed.body ?? "").trim()),
  };
}

/**
 * channel + send_mode + needs_human for a draft, resolved from the lead through
 * the same outreachDispatchFields() draft-all uses, so the two draft paths
 * cannot disagree about where a creator is reached.
 *
 * The request's hint only narrows it: 'email' forces email (an explicit ask the
 * old code also honoured), 'dm' is the legacy "their DM" stamp that
 * resolveOutreachChannel maps to the platform's DM, and anything else defers to
 * the lead's own primary_channel.
 */
function resolveDraftDispatch(
  requested: GenerateMessageInput["channel"],
  ctx: Pick<InfluencerContext, "primary_channel" | "platform" | "contact_email">
) {
  const primaryChannel =
    requested === "email" ? "email" : requested === "dm" ? "dm" : ctx.primary_channel;
  return outreachDispatchFields({
    primaryChannel,
    platform: ctx.platform,
    contactEmail: ctx.contact_email,
  });
}

export async function generateOutreachMessage(
  input: GenerateMessageInput
): Promise<GeneratedMessage> {
  const ctx = await loadInfluencerContext(input.sb, input.campaign_influencer_id);
  if (!ctx) throw new Error("Influencer context not found");

  // Gate FIRST: a refused creator costs zero model calls.
  const qualification = await resolveEligibility(input.sb, ctx);

  // The persisted channel comes from the LEAD, never from a literal. This used
  // to be `contact_email ? "email" : "dm"`, and 'dm' is not in migration 018's
  // CHECK on outreach_messages.channel — so every draft for an email-less
  // creator was an insert the database rejects.
  const dispatch = resolveDraftDispatch(input.channel, ctx);
  const channel = dispatch.channel;
  const messageType: MessageType = input.message_type || "initial";
  // Copy shape, not a persisted value. Anything that is not email is written as
  // a DM: the DM queue discards the subject, so the body has to stand alone.
  const draftChannel: "email" | "dm" = channel === "email" ? "email" : "dm";

  const releaseMs = ctx.release_date ? Date.parse(ctx.release_date) : NaN;
  const releasePast = Number.isFinite(releaseMs) && releaseMs < Date.now();
  // Only a negotiation names money, and only when a real estimate exists.
  const price = messageType === "negotiation" ? ctx.price_estimate_mid : null;
  // What that money is FOR. Resolved after the gate (a refused creator pays for
  // no reads) — and now for `initial` as well.
  //
  // It used to be skipped for the first touch on the grounds that the opening
  // ask was deliberately soft, so it should pay for no reads. That is what
  // produced "Would you be open to a paid post?": a question a creator cannot
  // answer, because a paid post could be a story, a reel, a sound-only use, for
  // a week or forever. Naming the package is the difference between a message
  // that can be triaged and one that gets deleted, and it costs one read that
  // resolveStandingDeliverables already caches nothing about either way.
  const packageAsk = describeDeliverables(await standingDeliverables(input.sb, ctx));

  // Authorship framing is judged where the verdict actually exists. The
  // initial path already ran checkDraftCopy inside generateOutreachDraft with
  // the reference guard's real creator_is_author verdict, so re-judging it
  // here on a guess would reject legitimate "your take on <someone else's
  // work>" copy. Thread copy cites no post, so there the strict assumption
  // (the creator authored their own work) is the safe one.
  const creatorIsAuthor = messageType !== "initial";

  const check = (draft: { subject: string | null; body: string }) =>
    checkOutreachCopy({
      subject: draft.subject,
      body: draft.body,
      artistName: ctx.artist_name,
      trackName: ctx.track_name,
      creatorBio: ctx.bio,
      creatorIsAuthor,
      releasePast,
      priceUsd: price,
      confidentialAmounts: [ctx.budget, ctx.per_influencer_cap],
    });

  let draft: { subject: string | null; body: string };
  let violations: string[] = [];
  let copySource: "model" | "fallback" = "model";

  if (messageType === "initial") {
    // THE hardened path. No second prompt exists for initial outreach.
    // Custom instructions ride the existing firmVoice seam (same trust level
    // as the firm's own voice profile) rather than a parallel prompt.
    // Campaign special_instructions ride the SAME seam as custom_instructions
    // (both are first-party label text, same trust level) rather than a third
    // parallel prompt path.
    const notes = labelNotes(ctx.special_instructions, input.custom_instructions);
    const firmVoice = notes
      ? `${ctx.voice_profile}\nExtra instructions from the label: ${notes}`
      : ctx.voice_profile;
    const recentPosts = (ctx.raw_data?.posts ?? []).slice(0, 5).map((p) => ({
      hook: (p.text ?? "").slice(0, 140),
      views: p.playCount,
      hashtags: (p.hashtags ?? [])
        .map((h) => h?.name ?? "")
        .filter((n) => n.length > 0)
        .slice(0, 5),
      postedAt: p.createTimeISO,
    }));
    // Everything the message needs to be answerable: who is writing, on whose
    // behalf, for exactly what, on which surface, and how to get out.
    const draftInput = {
      firmVoice,
      campaignId: ctx.campaign_id,
      artistName: ctx.artist_name,
      trackName: ctx.track_name ?? undefined,
      releaseDate: ctx.release_date ?? undefined,
      labelName: ctx.firm_name,
      senderName: ctx.sender_name,
      prefs: ctx.voice_prefs,
      channel: draftChannel,
      deliverables: packageAsk,
      platform: ctx.platform,
      // No replyAddress: the sending inbox is resolved at send time in
      // resend.ts, so the body says "reply with the word UNSUBSCRIBE" rather
      // than naming an address this layer would have to guess. The address goes
      // in the List-Unsubscribe header, which resend.ts owns.
      creator: { handle: ctx.username, bio: ctx.bio || undefined, recentPosts },
    };
    const generated = await generateOutreachDraft(draftInput);
    draft = generated;
    violations = check(generated);
    if (violations.length > 0) {
      // generateOutreachDraft already retried and fell back internally, so a
      // violation here is the money layer. Go straight to safe copy — the SAME
      // builder openai.ts degrades to, not a second hand-written copy of it.
      // The two used to be separate literals and they drifted: this one never
      // got the label name, the concrete ask, the sign-off or the opt-out.
      copySource = "fallback";
      const fb = buildFirstTouchFallback(draftInput);
      draft = {
        subject: fb.subject,
        body: appendOptOut(fb.body, { channel: draftChannel }),
      };
    }
  } else {
    const buildPrompt = (retry: string) =>
      (messageType === "follow_up"
        ? buildFollowUpPrompt(ctx, channel, packageAsk, labelNotes(ctx.special_instructions, input.custom_instructions))
        : buildNegotiationPrompt(ctx, channel, price, packageAsk, labelNotes(ctx.special_instructions, input.custom_instructions))) +
      retry;

    let candidate: { subject: string | null; body: string } | null = null;
    for (let attempt = 0; attempt < 2; attempt++) {
      const retry =
        attempt > 0 && violations.length > 0
          ? `\n\nYour previous attempt was rejected for: ${violations.join("; ")}. Fix every one of these.`
          : "";
      const generated = await generateJson(
        COPY_SYSTEM,
        buildPrompt(retry),
        messageType === "follow_up" ? "outreach.follow_up" : "outreach.negotiation",
        ctx.campaign_id
      );
      if (!generated.body) continue;
      const candidateDraft = {
        subject: channel === "email" ? generated.subject || null : null,
        body: generated.body,
      };
      violations = check(candidateDraft);
      if (violations.length === 0) {
        candidate = candidateDraft;
        break;
      }
    }
    if (candidate) {
      draft = candidate;
    } else {
      copySource = "fallback";
      const fb =
        messageType === "follow_up"
          ? fallbackFollowUp(ctx)
          : fallbackNegotiation(ctx, price, packageAsk);
      draft = { subject: fb.subject, body: fb.body };
    }
    // Every creator-facing message, not just the first one. A follow-up is the
    // message a creator is most likely to want out of, and it was the one with
    // no way out in it.
    draft = { ...draft, body: appendOptOut(draft.body, { channel: draftChannel }) };
  }

  return {
    subject: channel === "email" ? draft.subject : null,
    body: draft.body,
    ...dispatch,
    template_used: messageType,
    copy_source: copySource,
    violations: copySource === "fallback" ? violations : [],
    qualification,
  };
}

export async function saveOutreachMessage(
  sb: SupabaseClient,
  campaignInfluencerId: string,
  message: GeneratedMessage,
  messageType: string
): Promise<string> {
  // Get current message count for versioning
  const { count } = await sb
    .from("outreach_messages")
    .select("*", { count: "exact", head: true })
    .eq("campaign_influencer_id", campaignInfluencerId);

  const version = (count || 0) + 1;

  const { data, error } = await sb
    .from("outreach_messages")
    .insert({
      campaign_influencer_id: campaignInfluencerId,
      message_type: messageType,
      direction: "outbound",
      subject: message.subject,
      body: message.body,
      channel: message.channel,
      send_mode: message.send_mode,
      needs_human: message.needs_human,
      version,
      template_used: message.template_used,
      // Truthful provenance: a deterministic fallback is not model output, and
      // the active provider is not always OpenAI (MODEL_PROVIDER picks it).
      generation_model:
        message.copy_source === "fallback" ? "deterministic-fallback" : activeProviderName(),
      original_body: message.body,
    })
    .select("id")
    .single();

  if (error) throw new Error(`Failed to save message: ${error.message}`);

  // Update campaign_influencer outreach status and count
  await sb
    .from("campaign_influencers")
    .update({
      outreach_status: "draft_ready",
      message_count: version,
    })
    .eq("id", campaignInfluencerId);

  return data.id;
}

export function classifyResponse(responseText: string): {
  classification: string;
  confidence: number;
} {
  const lower = responseText.toLowerCase();

  // Strong positive signals
  const interestedKeywords = [
    "interested", "love to", "sounds great", "let's do it", "i'm in",
    "send me more", "tell me more", "what's the budget", "how much",
    "when do you need", "what would you need", "i'd be down", "count me in",
    "definitely", "yes", "for sure", "absolutely",
  ];

  // Strong negative signals
  const notInterestedKeywords = [
    "not interested", "no thanks", "pass", "don't do", "can't",
    "not for me", "not my thing", "too busy", "not taking",
    "stop", "unsubscribe", "remove me", "don't contact",
  ];

  // Negotiation signals
  const negotiationKeywords = [
    "rate", "fee", "price", "cost", "budget", "pay", "compensation",
    "how much", "what's the rate", "my rate is", "i charge",
    "negotiate", "deal", "terms", "contract",
  ];

  // Question signals
  const questionKeywords = [
    "what kind", "what type", "who is", "what genre",
    "tell me about", "more info", "more details", "?",
  ];

  const interestedScore = interestedKeywords.filter((k) => lower.includes(k)).length;
  const notInterestedScore = notInterestedKeywords.filter((k) => lower.includes(k)).length;
  const negotiationScore = negotiationKeywords.filter((k) => lower.includes(k)).length;
  const questionScore = questionKeywords.filter((k) => lower.includes(k)).length;

  const maxScore = Math.max(interestedScore, notInterestedScore, negotiationScore, questionScore);

  if (maxScore === 0) {
    return { classification: "unclear", confidence: 0.3 };
  }

  if (notInterestedScore >= maxScore) {
    return { classification: "not_interested", confidence: Math.min(0.5 + notInterestedScore * 0.15, 0.95) };
  }
  if (negotiationScore >= maxScore) {
    return { classification: "negotiating", confidence: Math.min(0.5 + negotiationScore * 0.12, 0.9) };
  }
  if (interestedScore >= maxScore) {
    return { classification: "interested", confidence: Math.min(0.5 + interestedScore * 0.15, 0.95) };
  }
  return { classification: "question", confidence: Math.min(0.4 + questionScore * 0.1, 0.8) };
}

// ── Opt-out detection ───────────────────────────────────────────────────────
//
// Separate from classifyResponse() on purpose, and much stricter.
//
// classifyResponse lumps "stop" and "unsubscribe" in with "too busy" and "pass"
// as `not_interested`, matches them by naive substring (`lower.includes("stop")`
// fires on "nonstop", "stopped", "can't stop listening"), and its only effect is
// campaign_influencers.outreach_status = 'rejected' for THAT campaign. The next
// campaign mails the same person again. That is the whole of the opt-out
// mechanism today, and every creator-facing message now tells creators to use
// it, so it has to become real.
//
// "Not interested in this one" and "never contact me again" are different
// requests and only the second one is an opt-out. An opt-out is destructive
// (pool-gates contactBlock refuses every future send from that label), so this
// is deliberately conservative: a missed opt-out still lands as
// `not_interested`, while a false positive silently deletes a willing creator
// from the label's pool for good.
//
// Wired in ingest-inbound.ts → firm-blocks.ts honourOptOut(): a
// firm_influencer_blocks row for the label the creator replied to (migration
// 056), falling back to the global influencers.blocklisted when that write is
// impossible.

/** Unambiguous do-not-contact phrases, matched on word boundaries. */
const OPT_OUT_PHRASES: RegExp[] = [
  /\bunsubscribe\b/i,
  /\bopt[\s-]?out\b/i,
  /\bremove me\b/i,
  /\btake me off\b/i,
  /\b(?:do not|don'?t)\s+(?:ever\s+)?(?:contact|message|email|dm|text)\s+me\b/i,
  /\bstop (?:contacting|messaging|emailing)\b/i,
];

/**
 * A bare "STOP" only counts when it is the whole message.
 *
 * That is how people actually send it, and the alternative — matching "stop"
 * anywhere — blocklists the creator who writes "I can't stop listening to this".
 */
const BARE_STOP = /^(?:please\s+)?stop(?:\s+please)?$/i;

export function isOptOutReply(text: string | null | undefined): boolean {
  if (!text) return false;
  const t = text.trim();
  if (t.length === 0) return false;
  if (OPT_OUT_PHRASES.some((re) => re.test(t))) return true;
  const bare = t.replace(/[.!?,;:\s]+$/g, '').replace(/^[\s"'“‘]+/, '');
  return BARE_STOP.test(bare);
}

// Map response classification to pipeline status
export function classificationToStatus(classification: string): string {
  switch (classification) {
    case "interested":
      return "responded";
    case "negotiating":
      return "negotiating";
    case "not_interested":
      return "rejected";
    case "question":
      return "responded";
    default:
      return "responded";
  }
}
